#!/usr/bin/env bash
# Writes apple/tests/unit/ReplicaSchema.swift from a snapshot the server
# served (GET /sync/snapshot): the projection's tables, views and indexes
# as the file declares them, and its rows; and apple/sources/kit/
# ReplicaShipped.swift: each table and view with its columns, which a
# launch holds the replica to. Run it on a snapshot of the server's seeded
# test fixture whenever the sync schema changes.
set -euo pipefail
snapshot="${1:?usage: replica-schema.sh <snapshot.sqlite>}"
cd "$(dirname "$0")/../.."
out=apple/tests/unit/ReplicaSchema.swift
shipped=apple/sources/kit/ReplicaShipped.swift

# Indented to the closing delimiter, which the literal strips; trailing
# blanks are escaped, as the formatters would strip them.
literal() {
    perl -pe 's/^/        /; s/([ \t]+)$/join "", map { $_ eq " " ? "\\#u{20}" : "\\#t" } split \/\/, $1/e'
}

{
    echo '// Generated by apple/scripts/replica-schema.sh; do not edit.'
    echo '// swiftlint:disable file_length line_length type_body_length'
    echo
    echo '/// Sync schema 1 as the server ships it, and the rows of a snapshot of'
    echo "/// the server's seeded test fixture."
    echo 'enum ReplicaSchema {'
    echo '    static let v1 = #"""'
    sqlite3 "$snapshot" .schema | literal
    echo '        """#'
    echo
    echo '    static let sample = #"""'
    sqlite3 "$snapshot" .dump | grep '^INSERT INTO' | literal
    echo '        """#'
    echo '}'
    echo '// swiftlint:enable file_length line_length type_body_length'
} >"$out"

{
    echo '// Generated by apple/scripts/replica-schema.sh; do not edit.'
    echo '// swiftlint:disable line_length'
    echo
    echo 'extension Replica {'
    echo '    /// Each table and view of sync schema 1 as the server ships it, a line'
    echo '    /// each: its name, then its columns.'
    echo '    static let shippedSchema = """'
    sqlite3 "$snapshot" "SELECT m.name || ' ' || group_concat(p.name, ' ') FROM sqlite_master m,
        pragma_table_info(m.name) p WHERE m.type IN ('table', 'view') GROUP BY m.name ORDER BY m.name" | literal
    echo '        """'
    echo '}'
    echo '// swiftlint:enable line_length'
} >"$shipped"
